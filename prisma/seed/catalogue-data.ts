export type AttributeValue = string | number | boolean | readonly string[];

export interface AttributeDefinitionSeed {
  code: string;
  label: string;
  dataType: AttributeDataType;
  scope: AttributeScope;
  isRequired: boolean;
  isFilterable: boolean;
  isSearchable: boolean;
  allowedValues: readonly string[] | null;
}

export interface ProductTypeSeed {
  code: string;
  name: string;
  description: string;
  taxRateBasisPoints: number;
  attributeDefinitions: readonly AttributeDefinitionSeed[];
}

function productAttribute(
  code: string,
  label: string,
  dataType: AttributeDataType,
  flags: {
    isRequired?: boolean;
    isFilterable?: boolean;
    isSearchable?: boolean;
    allowedValues?: readonly string[];
  },
): AttributeDefinitionSeed {
  return {
    code,
    label,
    dataType,
    scope: 'PRODUCT',
    isRequired: flags.isRequired ?? false,
    isFilterable: flags.isFilterable ?? false,
    isSearchable: flags.isSearchable ?? false,
    allowedValues: flags.allowedValues ?? null,
  };
}

function variantOption(
  code: string,
  label: string,
  isRequired: boolean,
  allowedValues: readonly string[],
): AttributeDefinitionSeed {
  return {
    code,
    label,
    dataType: 'ENUM',
    scope: 'VARIANT_OPTION',
    isRequired,
    isFilterable: true,
    isSearchable: code === 'colour',
    allowedValues,
  };
}

